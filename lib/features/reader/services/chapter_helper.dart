  /// 为某本书生成连贯连续的 12 章标准 ChapterItem 列表
  static List<ChapterItem> getFallbackChapters(String bookTitle) {
    final names = getChapterNamesForBook(bookTitle);
    return List.generate(names.length, (i) {
      return ChapterItem(
        index: i,
        title: '第${i + 1}章 ${names[i]}',
        url: '',
        isCached: false,
      );
    });
  }

  /// 判断当前书籍是否具备预置的离线保真精品段落
  static bool hasPresetContent(String bookTitle) {
    final title = cleanTitle(bookTitle).toLowerCase();
    return title.contains('shiri') ||
        title.contains('十日') ||
        title.contains('daoti') ||
        title.contains('道诡') ||
        title.contains('jianlai') ||
        title.contains('剑来') ||
        title.contains('emofaze') ||
        title.contains('恶魔') ||
        title.contains('guimi') ||
        title.contains('诡秘');
  }

